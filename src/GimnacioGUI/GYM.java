    private void AjustarImag() {
        int ancho = jLabel2.getWidth();
        int alto = jLabel2.getHeight();

        if (fondoOriginal != null && ancho > 500 && alto > 0) {
            Image img = fondoOriginal.getImage();
            int originalAncho = fondoOriginal.getIconWidth();
            int originalAlto = fondoOriginal.getIconHeight();
            double factorEscala = Math.max((double) ancho / originalAncho, (double) alto / originalAlto);

            int nuevoAncho = (int) (originalAncho * factorEscala);
            int nuevoAlto = (int) (originalAlto * factorEscala);

            Image scaledImg = img.getScaledInstance(nuevoAncho, nuevoAlto, Image.SCALE_SMOOTH);

            jLabel2.setIcon(new ImageIcon(scaledImg));
            jLabel2.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
            jLabel2.setVerticalAlignment(javax.swing.SwingConstants.CENTER);
        }
    }

