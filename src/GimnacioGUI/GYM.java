    public GYM(Usuario usuarioActual) {
        this();
        this.usuarioActual = usuarioActual;
        aplicarPermisosPorRol();
        if (usuarioActual != null) {
            setTitle("GYM - Usuario: " + usuarioActual.getNombreUsuario()
                    + " (" + usuarioActual.getRolUsuario() + ")");
        }
    }

    private void iniciarHiloAlertasMembresia() {
        FabricaRepositorios fabrica = new FabricaRepositorios(TipoRepositorio.MYSQL);
        FachadaGimnasio facade = new FachadaGimnasio(fabrica);
        List<Cliente> clientes = facade.getServicioCliente().listarTodos();

        hiloAlertas = new AlertaVencimientoMembresia(
                clientes,
                5,
                30_000L,
                mensaje -> JOptionPane.showMessageDialog(this,
                        mensaje,
                        "Alerta de membresía",
                        JOptionPane.WARNING_MESSAGE)
        );
        hiloAlertas.start();
    }

    private void aplicarPermisosPorRol() {
        if (usuarioActual == null || usuarioActual.getRolUsuario() == null) {
            return;
        }

        RolUsuario rol = usuarioActual.getRolUsuario();

        txtClaseCliente.setEnabled(false);

        switch (rol) {

            case ADMINISTRADOR:

                txtUsuiarios.setEnabled(true);
                txtEntrenadores.setEnabled(true);
                txtClases.setEnabled(true);
                txtPagos.setEnabled(true);
                txtRegistroClientes.setEnabled(true);
                txtCerrarSesion.setEnabled(true);

                txtClaseCliente.setEnabled(true);
                break;

            case ENTRENADOR:

                txtUsuiarios.setEnabled(false);
                txtPagos.setEnabled(false);
                txtEntrenadores.setEnabled(true);
                txtClases.setEnabled(true);
                txtRegistroClientes.setEnabled(true);
                txtCerrarSesion.setEnabled(true);

                txtClaseCliente.setEnabled(false);
                break;

            case CAJERO:

                txtUsuiarios.setEnabled(false);
                txtEntrenadores.setEnabled(false);
                txtClases.setEnabled(false);
                txtPagos.setEnabled(true);
                txtRegistroClientes.setEnabled(true);
                txtCerrarSesion.setEnabled(true);

                txtClaseCliente.setEnabled(false);
                break;

            case RECEPCIONISTA:

                txtUsuiarios.setEnabled(false);
                txtPagos.setEnabled(false);
                txtEntrenadores.setEnabled(true);
                txtClases.setEnabled(true);
                txtRegistroClientes.setEnabled(true);
                txtCerrarSesion.setEnabled(true);

                txtClaseCliente.setEnabled(true);
                break;

            default:

                txtUsuiarios.setEnabled(false);
                txtEntrenadores.setEnabled(false);
                txtClases.setEnabled(false);
                txtPagos.setEnabled(false);
                txtRegistroClientes.setEnabled(false);
                txtCerrarSesion.setEnabled(true);

                txtClaseCliente.setEnabled(false);
                break;
        }
    }

