    private void txtCerrarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtCerrarSesionActionPerformed
        int opcion = JOptionPane.showConfirmDialog(
                this,
                "¿Desea cerrar sesión?",
                "Cerrar Sesión",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );

        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }

        javax.swing.JDesktopPane desktop = this.getDesktopPane();

        if (hiloAlertas != null) {
            hiloAlertas.detener();
            hiloAlertas = null;
        }

        for (javax.swing.JInternalFrame frame : desktop.getAllFrames()) {
            frame.dispose();
        }

        txtUsuiarios.setEnabled(false);
        txtEntrenadores.setEnabled(false);
        txtClases.setEnabled(false);
        txtPagos.setEnabled(false);
        txtRegistroClientes.setEnabled(false);
        txtCerrarSesion.setEnabled(false);
        this.usuarioActual = null;
        this.setTitle("GYM");

        Login login = new Login();
        desktop.add(login);
        int x = (desktop.getWidth() - login.getWidth()) / 2;
        int y = (desktop.getHeight() - login.getHeight()) / 2;
        login.setLocation(Math.max(x, 0), Math.max(y, 0));

        login.setVisible(true);

        try {

            login.setSelected(true);

        } catch (java.beans.PropertyVetoException ex) {
        }
    }//GEN-LAST:event_txtCerrarSesionActionPerformed

